"""Gunicorn WSGI entrypoint: the viewer at /map, a status at /status, MapProxy's WMTS behind the sheet fetch.

A detail tile (zoom >= sheets.detail_zoom) is rendered only while every sheet under it is on disk and held
(store.holding): a first view of an area waits for its sheets (~3.5 s each, several at once), and a sheet
that cannot be fetched is a 502, never a tile drawn with a hole that MapProxy would keep. Lower zooms come
from the overview and never fetch. mapproxy.yaml is generated by entrypoint.py before this module loads.
"""
import json
import os
import re

from mapproxy.wsgiapp import make_wsgi_app

import sheets as S
from config import Config
from store import SheetMissing, Store

_mapproxy = make_wsgi_app("/app/mapproxy.yaml")
_VIEWER = "/app/leaflet.html"
_cfg = Config.from_env()
_known = S.load()
_detail = S.detail_zoom(_cfg.crossover)
_store = Store(_cfg.data_dir, _cfg.state_dir, _cfg.sheets_url, _cfg.fetch_jobs)
_TILE = re.compile(r"^/wmts/oi/webmercator/(\d+)/(\d+)/(\d+)\.(png|jpeg|jpg)$")


def _reply(start_response, status: str, body: bytes, ctype: str = "text/plain; charset=utf-8"):
    start_response(status, [("Content-Type", ctype), ("Content-Length", str(len(body)))])
    return [body]


def application(environ, start_response):
    path = environ.get("PATH_INFO", "")
    if path in ("/map", "/map/"):
        try:
            body = open(_VIEWER, "rb").read()
        except OSError:
            return _reply(start_response, "404 Not Found", b"leaflet.html not found")
        return _reply(start_response, "200 OK", body, "text/html; charset=utf-8")
    if path == "/status":
        pending = _store.pending_overview()
        doc = {"sheets_known": len(_known), "held_bytes": _store.held_bytes(), "budget_bytes": _cfg.budget_bytes,
               "overview_pending": len(pending), "detail_zoom": _detail,
               "overview_bytes": os.path.getsize(_cfg.overview) if os.path.exists(_cfg.overview) else None}
        with _store._db() as con:
            doc["sheets_held"] = con.execute("SELECT COUNT(*) FROM sheets").fetchone()[0]
        return _reply(start_response, "200 OK", json.dumps(doc).encode(), "application/json")
    if path.startswith("/wmts/") and "/1.0.0/" not in path:
        m = _TILE.match(path)
        if not m:
            return _reply(start_response, "404 Not Found", b"tiles are /wmts/oi/webmercator/{z}/{x}/{y}.png")
        z, x, y = (int(v) for v in m.groups()[:3])
        if z >= _detail:
            try:
                with _store.holding(S.ids_for_tile(z, x, y, _known)):
                    return list(_mapproxy(environ, start_response))
            except SheetMissing as e:
                return _reply(start_response, "502 Bad Gateway", f"sheet not fetched: {e}".encode())
    return _mapproxy(environ, start_response)
