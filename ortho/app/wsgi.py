"""Gunicorn WSGI entrypoint: the viewer at /map, a status at /status, MapProxy's WMTS behind the sheet fetch.

A detail tile (zoom >= sheets.detail_zoom) is rendered only once every sheet under it is on disk. Until then
(store.begin) its sheets download in the background and it is answered at once: 503 with Retry-After (the
download time to expect) and X-Ortho-Cost (the downloads this ask started); the client comes back. A sheet
that cannot be fetched is a 502 and a full store a 503 without Retry-After, never a tile drawn with a hole
that MapProxy would keep.

Every tile drawn says what it cost in X-Ortho-Cost: 1 when it was drawn, 0 when taken from the cache. Earth charges that to the client's budget (earth/limits.py): this service sees only earth. Lower zooms come
from the overview and never fetch. mapproxy.yaml is generated by entrypoint.py before this module loads.
"""
import json
import os
import re

from mapproxy.wsgiapp import make_wsgi_app

import overview
import sheets as S
from config import DIRECT_FROM_ZOOM, DIRECT_LAYER, Config
from store import SheetMissing, Store, StoreFull

_cfg = Config.from_env()
_mapproxy = make_wsgi_app(_cfg.mapproxy_yaml)
_VIEWER = "/app/leaflet.html"
_known = S.load()
_detail = S.detail_zoom(_cfg.crossover)
_store = Store.of(_cfg)
_TILE = re.compile(r"^/wmts/oi/webmercator/(\d+)/(\d+)/(\d+)\.(png|jpeg|jpg)$")


def _reply(start_response, status: str, body: bytes, ctype: str = "text/plain; charset=utf-8", extra=()):
    start_response(status, [("Content-Type", ctype), ("Content-Length", str(len(body))), *extra])
    return [body]


def application(environ, start_response):
    path = environ.get("PATH_INFO", "")
    if path in ("/map", "/map/"):
        try:
            body = open(_VIEWER, "rb").read()
        except OSError:
            return _reply(start_response, "404 Not Found", b"leaflet.html not found")
        return _reply(start_response, "200 OK", body, "text/html; charset=utf-8")
    if path == "/status":
        pending = _store.pending_overview()
        doc = {"sheets_known": len(_known), "held_bytes": _store.held_bytes(), "budget_bytes": _cfg.budget_bytes,
               "min_free_bytes": _cfg.min_free_bytes, "full": _store.full(),
               "overview_pending": len(pending), "detail_zoom": _detail,
               "overview_bytes": os.path.getsize(_cfg.overview) if os.path.exists(_cfg.overview) else None}
        with _store._db() as con:
            doc["sheets_held"] = con.execute("SELECT COUNT(*) FROM sheets").fetchone()[0]
        return _reply(start_response, "200 OK", json.dumps(doc).encode(), "application/json")
    if path.startswith("/wmts/") and "/1.0.0/" not in path:
        m = _TILE.match(path)
        if not m:
            return _reply(start_response, "404 Not Found", b"tiles are /wmts/oi/webmercator/{z}/{x}/{y}.png")
        z, x, y = (int(v) for v in m.groups()[:3])
        if z >= _detail:
            try:
                waiting = _store.begin(S.ids_for_tile(z, x, y, _known))
            except StoreFull as e:
                return _reply(start_response, "503 Service Unavailable", str(e).encode())
            except SheetMissing as e:
                return _reply(start_response, "502 Bad Gateway", f"sheet not fetched: {e}".encode())
            if waiting is not None:
                # its sheets are downloading: come back then, nobody holds a worker for it (recon pl04). The
                # cost is the downloads this ask started.
                started, after = waiting
                return _reply(start_response, "503 Service Unavailable",
                              f"its sheets are downloading; retry in {after} s".encode(),
                              extra=[("Retry-After", str(after)), ("X-Ortho-Cost", str(started))])
        drawn = z >= DIRECT_FROM_ZOOM or not overview.cache_file(_cfg.tile_cache, z, x, y).exists()
        cost = str(int(drawn))
        if z >= DIRECT_FROM_ZOOM:                      # the layer whose cache stores nothing (config.py)
            environ = {**environ, "PATH_INFO": path.replace("/wmts/oi/", f"/wmts/{DIRECT_LAYER}/", 1)}

        def start_with_cost(status, headers, exc_info=None):
            return start_response(status, [*headers, ("X-Ortho-Cost", cost)], exc_info)
        return _mapproxy(environ, start_with_cost)
    return _mapproxy(environ, start_response)
